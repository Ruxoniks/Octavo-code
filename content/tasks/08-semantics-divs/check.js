check('header', 'У страницы есть шапка', function (t) {
  var head = t.$('header');
  t.assert(
    head,
    'Тега <header> на странице нет. Шапка — первое, что программа чтения вслух объявляет человеку: «здесь название и навигация, основное дальше».',
  );
  t.assert(
    head.querySelector('h1'),
    'Тег <header> есть, но заголовок «Восьмая полоса» остался снаружи. Шапкой нужно обернуть именно тот блок, в котором лежит <h1>.',
  );
  t.assert(
    head.className.indexOf('masthead') !== -1,
    'У <header> пропал class="masthead" — вместе с ним пропало и оформление. Тег меняем, класс оставляем.',
  );
  return 'Шапка названа своим тегом';
});

check('main', 'Основное содержимое одно', function (t) {
  var count = t.count('main');
  t.assert(
    count > 0,
    'Тега <main> на странице нет. Именно к нему программа чтения умеет прыгать сразу, чтобы человек не выслушивал шапку на каждой странице сайта.',
  );
  t.assert(
    count === 1,
    'Тегов <main> на странице: ' + count + '. Основное содержимое у страницы одно — иначе непонятно, к какому из них прыгать.',
  );
  t.assert(
    t.count('main .note') >= 3,
    'Заметки оказались снаружи <main>. Основным содержимым газеты нужно обернуть блок с новостями целиком.',
  );
  return 'Основное содержимое названо';
});

check('footer', 'У страницы есть подвал', function (t) {
  var foot = t.$('footer');
  t.assert(
    foot,
    'Тега <footer> нет. Подвал — служебная часть: выходные данные, адрес редакции. Названный подвал программа чтения может пропустить, безымянный див ей придётся зачитать.',
  );
  t.assert(
    t.text(foot).length > 10,
    'Подвал пустой. Оберни им блок с выходными данными газеты, а не пустое место.',
  );
  return 'Подвал назван своим тегом';
});

check('no-nameless-wrappers', 'Безымянных обёрток не осталось', function (t) {
  var leftovers = [];
  if (t.$('div.masthead')) leftovers.push('div.masthead');
  if (t.$('div.content')) leftovers.push('div.content');
  if (t.$('div.colophon')) leftovers.push('div.colophon');

  t.assert(
    leftovers.length === 0,
    'Ещё остались безымянные обёртки: ' +
      leftovers.join(', ') +
      '. Класс подсказывает тебе, тег подсказывает всем остальным.',
  );
  return 'Все три опоры страницы названы';
});

check('text-intact', 'Текст газеты на месте', function (t) {
  t.assert(
    t.text('h1').length > 3,
    'Заголовок газеты пропал. В этом задании меняются только имена тегов — текст трогать не нужно.',
  );
  t.assert(
    t.count('.note') >= 3,
    'Заметок на полосе: ' + t.count('.note') + ', а было три. Похоже, при правке потерялся кусок разметки — нажми «Начать заново» и попробуй ещё раз.',
  );
  return 'Полоса цела: заметок ' + t.count('.note');
});
